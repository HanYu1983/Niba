app.config = async function () {
  const rows = parseCSV(getDictionryCSV())
  // 長文字優先
  rows.sort((a, b) => b["読み"].length - a["読み"].length)
  const words = rows.map(i => i["読み"])
  return {
    words: words,
    lookupKanji(word) {
      const ret = rows.find(i => i["読み"] == word)?.["漢字表記"]
      if (ret == null) {
        throw new Error(`word not found kanzi: ${word}`)
      }
      return ret
    },
    checkWordsAndGetIdxAryList(wordWantCheck) {
      const ret = []
      for (let i = 0; i < wordWantCheck.length; ++i) {
        const subWorkWantCheck = wordWantCheck.substr(i)
        const matchedWord = this.words.filter(word => subWorkWantCheck.startsWith(word))?.[0]
        if (matchedWord) {
          ret.push(R.range(i, i + matchedWord.length))
        }
      }
      return ret
    },
    convertIdxAryToWord(wordWantCheck, idxAry) {
      return idxAry.map(i => wordWantCheck[i]).join("")
    },
    getFontStr() {
      return "Arial"
    },
    getGameTime() {
      return 30000
    },
    getComboColor(combo) {
      const colors = [
        [176, 190, 197, 100],
        [66, 165, 245, 100],
        [102, 187, 106, 100],
        [255, 167, 38, 100],
        [239, 83, 80, 100]
      ]
      return colors[combo % colors.length]
    }
  }
}()

function parseCSV(csv) {
  const lines = csv.split('\n');
  const result = [];
  const headers = lines[0].split(',');
  for (let i = 1; i < lines.length; i++) {
    const obj = {};
    const currentLine = lines[i].split(',');
    for (let j = 0; j < headers.length; j++) {
      obj[headers[j].trim()] = currentLine[j] ? currentLine[j].trim() : '';
    }
    result.push(obj);
  }
  return result;
}

