/** 取得資源點在地圖上的顯示圖示；輜重庫維持專屬圖示。 */
export function getResourcePointIcon(name: string, terrain: string | undefined): string {
  if (name === '輜重庫') return '🏮'
  return resourceIcons[terrain ?? ''] ?? resourceIcons.default ?? '💠'
}